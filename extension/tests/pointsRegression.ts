import assert from 'node:assert/strict';
import { loadPoints, savePoints, PointBackupSchema } from '../src/storage/points';
const store:Record<string,unknown>={};
Object.defineProperty(globalThis,'chrome',{value:{storage:{local:{get:async(key:string)=>({[key]:store[key]}),set:async(value:object)=>Object.assign(store,structuredClone(value))}}},configurable:true});
const a='a'.repeat(64),b='b'.repeat(64),point={id:'1',name:'Introdução',frame:300,fpsNumerator:30,fpsDenominator:1};
assert.deepEqual(await loadPoints(a),{version:0,points:[]});
await savePoints(a,0,[point]);
assert.deepEqual((await loadPoints(a)).points,[point]);
assert.deepEqual((await loadPoints(b)).points,[]);
await assert.rejects(savePoints(a,0,[]),/outro painel/);
assert.equal((await loadPoints(a)).points.length,1);
await assert.rejects(savePoints(a,1,[point,point]));
await assert.rejects(savePoints(a,1,[{...point,frame:-1}]));
await assert.rejects(savePoints(a,1,[{...point,fpsDenominator:0}]));
assert.equal(PointBackupSchema.safeParse({format:'wide-studio-points',version:1,projectName:'Demo',points:[point]}).success,true);
assert.equal(PointBackupSchema.safeParse({format:'wide-studio-points',version:2,projectName:'Demo',points:[point]}).success,false);
assert.equal(PointBackupSchema.safeParse({format:'wide-studio-points',version:1,projectName:'Demo',points:[{...point,code:'alert(1)'}]}).success,false);
store[`wide-studio:points:v1:${a}`]={version:2,points:'corrupted'};
await assert.rejects(loadPoints(a),/Não foram sobrescritos/);
await assert.rejects(savePoints(a,2,[]),/Não foram sobrescritos/);
assert.deepEqual(store[`wide-studio:points:v1:${a}`],{version:2,points:'corrupted'});
await assert.rejects(loadPoints('not-a-project'));
console.log('15 points regression checks passed (local storage fixture).');
