import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
const win=new Window({url:'https://wide.video/app/1.7.12/'});
for(const key of ['window','document','Event'])Object.defineProperty(globalThis,key,{value:key==='window'?win:(win as any)[key],configurable:true});
let requests=0;
Object.defineProperty(globalThis,'chrome',{value:{runtime:{getURL:(p:string)=>`chrome-extension://test/${p}`,sendMessage:async()=>{requests++;}}},configurable:true});
const {toggleOverlay,mountOverlayLauncher}=await import('../src/content/overlay');
mountOverlayLauncher();
assert.equal(requests,0);assert.equal(win.document.querySelectorAll('#wide-studio-overlay').length,1);
const url='chrome-extension://test/sidepanel.html?editorTabId=12';
assert.equal(toggleOverlay(url)?.open,true);assert.equal(win.document.documentElement.hasAttribute('data-wide-studio-docked'),true);
assert.equal(toggleOverlay()?.open,false);assert.equal(win.document.documentElement.hasAttribute('data-wide-studio-docked'),false);
toggleOverlay(url);assert.equal(win.document.querySelectorAll('#wide-studio-overlay').length,1);
assert.throws(()=>toggleOverlay('https://attacker.invalid/sidepanel.html'));
assert.throws(()=>toggleOverlay('chrome-extension://other/sidepanel.html'));
assert.throws(()=>toggleOverlay('chrome-extension://test/other.html'));
win.document.querySelector('#wide-studio-overlay')!.remove();mountOverlayLauncher();
assert.equal(win.document.querySelectorAll('#wide-studio-overlay').length,1);
assert.equal(win.document.documentElement.hasAttribute('data-wide-studio-docked'),false);
await win.happyDOM.close();console.log('12 overlay regression checks passed (simulated DOM).');
